import { useEffect, useState } from 'react'
import { useTranslation } from 'react-i18next'
import { formatUseTime } from '@/lib/format'

export function PendingLogTiming(props: { startedAt: number }) {
  const { t } = useTranslation()
  const [now, setNow] = useState(() => Date.now())
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), 1000)
    return () => clearInterval(timer)
  }, [])
  return (
    <span
      className='font-mono text-xs text-amber-600 tabular-nums dark:text-amber-400'
      aria-label={t('usageLogs.inProgress')}
    >
      {formatUseTime(Math.max(0, Math.floor(now / 1000) - props.startedAt))}
    </span>
  )
}
